        // ── Pluralization helper ──────────────────────────────────────────────────

        /// <summary>Returns the correctly pluralized "key" word for the given count.</summary>
        public static string KeysText(int n)
        {
            var lang = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName;
            switch (lang)
            {
                // Slavic 3-form: ru / be
                case "ru":
                case "be":
                    return n % 10 == 1 && n % 100 != 11 ? Get(KeySingular)
                         : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20) ? Get(KeyFew)
                         : Get(KeyMany);
                // Ukrainian 3-form
                case "uk":
                    return n % 10 == 1 && n % 100 != 11 ? Get(KeySingular)
                         : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20) ? Get(KeyFew)
                         : Get(KeyMany);
                // Romanian: 1 singular, 2–19 few, 20+ many
                case "ro":
                    return n == 1 ? Get(KeySingular)
                         : n < 20  ? Get(KeyFew)
                         : Get(KeyMany);
                // All other languages: singular vs plural
                default:
                    return n == 1 ? Get(KeySingular) : Get(KeyMany);
            }
        }

