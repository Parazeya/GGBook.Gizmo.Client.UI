        public static string Get(string key)
        {
            var culture = CultureInfo.CurrentUICulture;

            // 1. Exact: "ru-RU"
            if (TryGet(culture.Name, key, out var val)) return val;

            // 2. Language only: "ru"
            if (TryGet(culture.TwoLetterISOLanguageName, key, out val)) return val;

            // 3. English fallback
            if (_strings.TryGetValue("en", out var en) && en.TryGetValue(key, out val)) return val!;

            return key;
        }

        private static bool TryGet(string culture, string key, out string value)
        {
            if (_strings.TryGetValue(culture, out var dict) && dict.TryGetValue(key, out value!))
                return true;
            value = null!;
            return false;
        }
